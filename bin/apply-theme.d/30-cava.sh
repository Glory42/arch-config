# cava's gradient, reloaded with USR2
if command -v cava >/dev/null 2>&1; then
    mkdir -p ~/.config/cava/themes
    {
        echo "# Generated by bin/apply-theme from palette.json, do not edit"
        echo "[color]"
        echo "gradient = 1"
        n=1
        for p in 0 12 24 38 52 66 80 94; do
            echo "gradient_color_$n = '#$(mix "$accent" "$fg" "$p")'"
            n=$((n + 1))
        done
    } > ~/.config/cava/themes/apollo
    pgrep -x cava | xargs -r kill -USR2
fi
